-- The calculator's tables: the people who use it (users, roles and permissions, logins, one-time links, the
-- activity log), their settings, their share trades and CGT settings, and the ECB's exchange rates kept once fetched.
-- Runs on PostgreSQL, and on H2 in its PostgreSQL mode.

create table permissions (
    id bigint generated by default as identity primary key,
    name varchar(255) not null unique
);

create table roles (
    id bigint generated by default as identity primary key,
    created_at timestamp(6) with time zone not null,
    name varchar(255) not null unique
);

create table role_has_permissions (
    role_id bigint not null references roles (id),
    permission_id bigint not null references permissions (id),
    primary key (role_id, permission_id)
);
create index role_has_permissions_permission_id on role_has_permissions (permission_id);

create table users (
    id bigint generated by default as identity primary key,
    created_at timestamp(6) with time zone not null,
    email varchar(255) not null unique,
    name varchar(255) not null,
    password varchar(255) not null,
    email_verified_at timestamp(6) with time zone,
    invitation_pending boolean,
    verification_required boolean
);

create table model_has_roles (
    user_id bigint not null references users (id),
    role_id bigint not null references roles (id),
    primary key (user_id, role_id)
);
create index model_has_roles_role_id on model_has_roles (role_id);

create table refresh_tokens (
    id bigint generated by default as identity primary key,
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    family varchar(36) not null,
    revoked_at timestamp(6) with time zone,
    rotated boolean,
    token_hash varchar(64) not null unique,
    user_id bigint not null references users (id)
);
create index refresh_tokens_expires_at on refresh_tokens (expires_at);
create index refresh_tokens_family on refresh_tokens (family);
create index refresh_tokens_user_id on refresh_tokens (user_id);

create table one_time_tokens (
    id bigint generated by default as identity primary key,
    created_at timestamp(6) with time zone not null,
    expires_at timestamp(6) with time zone not null,
    purpose varchar(32) not null check (purpose in ('PASSWORD_RESET', 'EMAIL_VERIFICATION', 'INVITATION')),
    token_hash varchar(64) not null unique,
    used_at timestamp(6) with time zone,
    user_id bigint not null references users (id)
);
create index one_time_tokens_user_id on one_time_tokens (user_id);

create table activity_log (
    id bigint generated by default as identity primary key,
    action varchar(64) not null,
    actor varchar(255) not null,
    at timestamp(6) with time zone not null,
    details varchar(1000) not null,
    ip varchar(255) not null,
    target varchar(255) not null
);
create index activity_log_at on activity_log (at);

-- each user's settings, as the browser saves them (key and JSON value)
create table user_settings (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users (id) on delete cascade,
    setting_key varchar(60) not null,
    setting_value varchar(100000) not null,
    updated_at timestamp(6) with time zone not null,
    constraint user_settings_user_key unique (user_id, setting_key)
);

-- a user's share trades: buys, sells and splits; amounts as entered (in their currency, and in euro at the rate used),
-- and the ECB's rate of the day, looked up as each is saved
create table share_trades (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users (id) on delete cascade,
    kind varchar(5) not null,
    trade_date date not null,
    symbol varchar(20) not null,
    name varchar(100),
    asset varchar(10) not null,
    owner varchar(10) not null,
    quantity numeric(20, 8) not null,
    amount numeric(30, 12) not null,
    currency varchar(3) not null,
    eur_rate numeric(24, 12),
    amount_eur numeric(30, 12) not null,
    fees numeric(24, 8) not null,
    fees_eur numeric(24, 8) not null,
    cost_eur numeric(18, 4),
    source varchar(10),
    note varchar(200),
    entered_in varchar(10) not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    ecb_rate numeric(24, 12),
    ecb_rate_date date
);
create index share_trades_user_id on share_trades (user_id, trade_date);

-- losses brought forward from before the trades entered
create table cgt_settings (
    user_id bigint primary key references users (id) on delete cascade,
    losses_before numeric(20, 2) not null
);

-- the ECB's euro reference rates (units of a currency per euro), kept once fetched
create table fx_rates (
    currency varchar(3) not null,
    rate_date date not null,
    rate numeric(20, 8) not null,
    primary key (currency, rate_date)
);
